import assert from 'node:assert/strict';
import {createShopMessage,parseShopMessage,shopMessageMarkup,normalizeShopItem,shopItemHash} from '../src/shop-message.mjs';
import {messagePreview} from '../src/message-preview.js';
const item={kind:'offer',id:'offer-12345',name:'Day-o 🎵',type:'Emote',price:500,image:'https://fortnite-api.com/images/cosmetics/br/eid_asidedepot/icon.png'};
const text=createShopMessage(item);
assert.deepEqual(parseShopMessage(text),item);
assert.ok(text.length<4000);
assert.equal(messagePreview(text),'Shared Day-o 🎵 from Shop');
assert.equal(shopItemHash(item),'#item=offer-12345');
assert.equal(shopItemHash({...item,kind:'cosmetic',id:'cosmetic-br-Test'}),'#cosmetic=cosmetic-br-Test');
assert.ok(shopMessageMarkup(text).includes('View in Shop'));
assert.ok(shopMessageMarkup(createShopMessage({...item,name:'<img src=x onerror=alert(1)>'})).includes('&lt;img'));
for(const image of ['javascript:alert(1)','http://fortnite-api.com/a.png','https://fortnite-api.com.evil.test/a.png','https://user:pass@fortnite-api.com/a.png','data:image/svg+xml,x'])assert.equal(normalizeShopItem({...item,image}),null);
for(const price of [-1,Infinity,1.5,'500',undefined])assert.equal(normalizeShopItem({...item,price}),null);
assert.equal(parseShopMessage('[[vela-shop:1:invalidbase64]]'),null);
assert.equal(parseShopMessage(text+' extra'),null);
assert.equal(shopMessageMarkup('hello'),'');
assert.equal(parseShopMessage(createShopMessage({...item,price:null})).price,null);
console.log('PASS shop message round-trip, card escaping, host validation, invalid payloads, preview and deep links');
