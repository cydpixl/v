import {readFileSync} from 'node:fs';
import assert from 'node:assert/strict';
const file=path=>readFileSync(path,'utf8');
const html=file('public/daily-thoughts/index.html');
const bundle=file('public/daily-thoughts/assets/dt-updated.js');
const styles=file('public/daily-thoughts/assets/dt-updated.css');
const catalog=file('src/desktop-catalog.js');
const hub=file('src/hub.js');
const installs=file('src/app-installs.mjs');
const mount=file('src/daily-thoughts-app.mjs');
const icon=file('public/app-icons/daily-thoughts.svg');
assert.match(html,/<base href="\.\/"/);
assert.match(html,/src="\.\/assets\/dt-updated\.js"/);
assert.match(html,/href="\.\/assets\/dt-updated\.css"/);
assert.ok(styles.length>5000,'Daily Thoughts styles must be packaged');
assert.match(bundle,/le\.functions\.invoke\("dt-account"/);
