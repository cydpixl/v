import assert from 'node:assert/strict';
import {requestApiWithRecovery as request} from '../src/api-transport.mjs';
const primary='https://proxy.example.com',fallback='https://direct.example.com';
const ok=status=>({status});
const calls=[];
const fake=(url,init)=>{calls.push([url,init]);return Promise.resolve(ok(200));};
await request('/me',{method:'GET'},{primaryOrigin:primary,fallbackOrigin:fallback,fetcher:fake});
assert.equal(calls[0][0],fallback+'/api/me');
calls.length=0;
await request('/friends',{method:'GET'},{primaryOrigin:primary,fallbackOrigin:fallback,fetcher:(url,init)=>{calls.push([url,init]);return Promise.resolve(ok(calls.length===1?503:200));}});
assert.deepEqual(calls.map(x=>x[0]),[primary+'/api/friends',fallback+'/api/friends']);
calls.length=0;
const input={method:'PUT',headers:{Authorization:'Bearer token'},body:JSON.stringify({name:'Example',handle:'example'})};
await request('/me',input,{primaryOrigin:primary,fallbackOrigin:fallback,fetcher:(url,init)=>{calls.push([url,init]);return calls.length===1?Promise.reject(new TypeError('Failed to fetch')):Promise.resolve(ok(200));}});
assert.deepEqual(calls.map(x=>x[0]),[fallback+'/api/me',primary+'/api/me']);
assert.equal(calls[1][1],input);
calls.length=0;
assert.equal((await request('/me',{method:'GET'},{primaryOrigin:primary,fallbackOrigin:fallback,fetcher:url=>{calls.push(url);return Promise.resolve(ok(401));}})).status,401);
assert.equal(calls.length,1);
calls.length=0;
await assert.rejects(request('/conversations',{method:'POST'},{primaryOrigin:primary,fallbackOrigin:fallback,fetcher:url=>{calls.push(url);throw new TypeError('Failed to fetch');}}),/Your account is still signed in/);
assert.deepEqual(calls,[primary+'/api/conversations']);
calls.length=0;
await request('/state',{method:'GET'},{primaryOrigin:primary,fallbackOrigin:'',fetcher:url=>{calls.push(url);return Promise.resolve(ok(200));}});
assert.deepEqual(calls,[primary+'/api/state']);
console.log('PASS auth API failover, safe methods, no duplicate writes, 401 handling');
